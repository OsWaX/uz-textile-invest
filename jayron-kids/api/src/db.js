'use strict';
/**
 * Слой доступа к данным. СУБД — PostgreSQL.
 * Суммы хранятся в целых сумах (BIGINT), время — в timestamptz.
 */
const { AsyncLocalStorage } = require('node:async_hooks');
const { Pool, types } = require('pg');

const config = require('./config');

// BIGINT приходит строкой; суммы в сумах далеко от предела Number.MAX_SAFE_INTEGER.
types.setTypeParser(20, (value) => Number(value));

const pool = new Pool({
  connectionString: config.databaseUrl,
  max: config.dbPoolSize,
  idleTimeoutMillis: 30_000,
});

const txStorage = new AsyncLocalStorage();

const SCHEMA = `
CREATE TABLE IF NOT EXISTS categories (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug       TEXT NOT NULL UNIQUE,
  name_uz    TEXT NOT NULL,
  name_ru    TEXT NOT NULL,
  color      TEXT NOT NULL DEFAULT '#4FB6F2',
  kind       TEXT NOT NULL DEFAULT 'tshirt',
  sort       INTEGER NOT NULL DEFAULT 0,
  is_active  BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS products (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug            TEXT NOT NULL UNIQUE,
  category_id     INTEGER NOT NULL REFERENCES categories(id),
  name_uz         TEXT NOT NULL,
  name_ru         TEXT NOT NULL,
  description_uz  TEXT NOT NULL DEFAULT '',
  description_ru  TEXT NOT NULL DEFAULT '',
  material_uz     TEXT NOT NULL DEFAULT '',
  material_ru     TEXT NOT NULL DEFAULT '',
  gender          TEXT NOT NULL DEFAULT 'unisex' CHECK (gender IN ('boy', 'girl', 'unisex')),
  kind            TEXT NOT NULL DEFAULT 'tshirt',
  price           BIGINT NOT NULL CHECK (price > 0),
  old_price       BIGINT CHECK (old_price IS NULL OR old_price > 0),
  images          JSONB NOT NULL DEFAULT '[]'::jsonb,
  mxik            TEXT NOT NULL DEFAULT '',
  package_code    TEXT NOT NULL DEFAULT '',
  is_new          BOOLEAN NOT NULL DEFAULT FALSE,
  is_hit          BOOLEAN NOT NULL DEFAULT FALSE,
  is_active       BOOLEAN NOT NULL DEFAULT TRUE,
  sort            INTEGER NOT NULL DEFAULT 0,
  created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category_id);

-- Вариант товара — сочетание цвета и размера со своим остатком на складе
CREATE TABLE IF NOT EXISTS product_variants (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  sku            TEXT NOT NULL UNIQUE,
  size           TEXT NOT NULL,
  color_code     TEXT NOT NULL,
  color_hex      TEXT NOT NULL,
  color_name_uz  TEXT NOT NULL,
  color_name_ru  TEXT NOT NULL,
  stock          INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  UNIQUE (product_id, color_code, size)
);
CREATE INDEX IF NOT EXISTS idx_variants_product ON product_variants(product_id);

CREATE TABLE IF NOT EXISTS regions (
  code           TEXT PRIMARY KEY,
  name_uz        TEXT NOT NULL,
  name_ru        TEXT NOT NULL,
  courier_price  BIGINT,             -- NULL: курьерской доставки в регион нет
  post_price     BIGINT NOT NULL,
  post_days      TEXT NOT NULL DEFAULT '2-4',
  sort           INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS customers (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone         TEXT NOT NULL UNIQUE,
  name          TEXT NOT NULL DEFAULT '',
  language      TEXT NOT NULL DEFAULT 'uz' CHECK (language IN ('uz', 'ru')),
  last_address  JSONB,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS otp_codes (
  phone         TEXT PRIMARY KEY,
  code_hash     TEXT NOT NULL,
  expires_at    TIMESTAMPTZ NOT NULL,
  attempts      INTEGER NOT NULL DEFAULT 0,
  sent_at       TIMESTAMPTZ NOT NULL,
  window_start  TIMESTAMPTZ NOT NULL,
  window_count  INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash    TEXT PRIMARY KEY,
  role          TEXT NOT NULL CHECK (role IN ('customer', 'admin')),
  customer_id   INTEGER REFERENCES customers(id) ON DELETE CASCADE,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at    TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS promo_codes (
  code        TEXT PRIMARY KEY,
  kind        TEXT NOT NULL CHECK (kind IN ('percent', 'fixed')),
  value       BIGINT NOT NULL CHECK (value > 0),
  min_total   BIGINT NOT NULL DEFAULT 0,
  max_uses    INTEGER,
  used_count  INTEGER NOT NULL DEFAULT 0,
  ends_at     TIMESTAMPTZ,
  is_active   BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS orders (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
  customer_id      INTEGER NOT NULL REFERENCES customers(id),
  status           TEXT NOT NULL DEFAULT 'new'
                   CHECK (status IN ('new', 'confirmed', 'shipped', 'delivered', 'cancelled')),
  payment_method   TEXT NOT NULL CHECK (payment_method IN ('cash', 'payme', 'click')),
  payment_status   TEXT NOT NULL DEFAULT 'pending'
                   CHECK (payment_status IN ('pending', 'paid', 'cancelled', 'refunded')),
  delivery_method  TEXT NOT NULL CHECK (delivery_method IN ('courier', 'post', 'pickup')),
  region_code      TEXT REFERENCES regions(code),
  city             TEXT NOT NULL DEFAULT '',
  address          TEXT NOT NULL DEFAULT '',
  comment          TEXT NOT NULL DEFAULT '',
  recipient_name   TEXT NOT NULL,
  recipient_phone  TEXT NOT NULL,
  subtotal         BIGINT NOT NULL,
  discount         BIGINT NOT NULL DEFAULT 0,
  delivery_price   BIGINT NOT NULL DEFAULT 0,
  total            BIGINT NOT NULL,
  promo_code       TEXT,
  language         TEXT NOT NULL DEFAULT 'uz',
  stock_released   BOOLEAN NOT NULL DEFAULT FALSE,
  created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
  paid_at          TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders(customer_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);

CREATE TABLE IF NOT EXISTS order_items (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id       INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id     INTEGER NOT NULL REFERENCES products(id),
  variant_id     INTEGER NOT NULL REFERENCES product_variants(id),
  name_uz        TEXT NOT NULL,
  name_ru        TEXT NOT NULL,
  kind           TEXT NOT NULL,
  size           TEXT NOT NULL,
  color_hex      TEXT NOT NULL,
  color_name_uz  TEXT NOT NULL,
  color_name_ru  TEXT NOT NULL,
  image          TEXT,
  price          BIGINT NOT NULL,
  quantity       INTEGER NOT NULL CHECK (quantity > 0),
  mxik           TEXT NOT NULL DEFAULT '',
  package_code   TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items(order_id);

CREATE TABLE IF NOT EXISTS order_history (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id    INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  status      TEXT NOT NULL,
  note        TEXT NOT NULL DEFAULT '',
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_order_history_order ON order_history(order_id);

-- Транзакции платёжных систем. Суммы — в тийинах (1 сум = 100 тийинов).
CREATE TABLE IF NOT EXISTS payment_transactions (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider     TEXT NOT NULL CHECK (provider IN ('payme', 'click', 'demo')),
  external_id  TEXT NOT NULL,
  order_id     INTEGER NOT NULL REFERENCES orders(id),
  amount       BIGINT NOT NULL,
  state        INTEGER NOT NULL,
  reason       INTEGER,
  provider_time BIGINT,
  create_time  BIGINT NOT NULL,
  perform_time BIGINT NOT NULL DEFAULT 0,
  cancel_time  BIGINT NOT NULL DEFAULT 0,
  fiscal_data  JSONB,
  UNIQUE (provider, external_id)
);
CREATE INDEX IF NOT EXISTS idx_payment_tx_order ON payment_transactions(order_id);
`;

function client() {
  return txStorage.getStore() || pool;
}

async function query(sql, params = []) {
  return client().query(sql, params);
}

async function all(sql, params) {
  return (await query(sql, params)).rows;
}

async function get(sql, params) {
  return (await query(sql, params)).rows[0];
}

async function run(sql, params) {
  const result = await query(sql, params);
  return { changes: result.rowCount, row: result.rows[0] };
}

/**
 * Выполняет fn в транзакции. Вложенные вызовы используют ту же транзакцию.
 */
async function transaction(fn) {
  if (txStorage.getStore()) return fn();
  const conn = await pool.connect();
  try {
    await conn.query('BEGIN');
    const result = await txStorage.run(conn, fn);
    await conn.query('COMMIT');
    return result;
  } catch (error) {
    await conn.query('ROLLBACK').catch(() => {});
    throw error;
  } finally {
    conn.release();
  }
}

let initialized = false;
async function init(force = false) {
  if (initialized && !force) return;
  // Блокировка не даёт двум процессам создавать схему одновременно
  await transaction(async () => {
    await query('SELECT pg_advisory_xact_lock(424242)');
    await query(SCHEMA);
  });
  initialized = true;
}

const close = () => pool.end();

module.exports = { pool, query, all, get, run, transaction, init, close };
