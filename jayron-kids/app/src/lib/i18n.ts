export const dictionaries: Record<Lang, Dictionary> = { uz, ru };

/** Подставляет значения {name} в строку перевода. */
export function translate(lang: Lang, key: TextKey, vars?: Record<string, string | number>): string {
  let text = dictionaries[lang][key] ?? dictionaries.uz[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

export const pick = (lang: Lang, value: Localized | null | undefined): string => (value ? value[lang] || value.uz : '');

